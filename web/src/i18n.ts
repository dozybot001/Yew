const dictionaries: Record<Lang, Record<MessageKey, string>> = { zh, en };

let current: Lang = "zh";
const listeners = new Set<() => void>();

export function systemLang(): Lang {
	return navigator.language.toLowerCase().startsWith("zh") ? "zh" : "en";
}

export function setLang(lang: Lang): void {
	if (lang === current) return;
	current = lang;
	document.documentElement.lang = lang === "zh" ? "zh-CN" : "en";
	for (const listener of listeners) listener();
}

export function getLang(): Lang {
	return current;
}

/** Whether a key built at run time, such as a tool's name, has a message. */
export function hasMessage(key: string): key is MessageKey {
	return Object.hasOwn(zh, key);
}

/** A permission mode's hint, as commands run now: in the system sandbox, or as the person. */
export function permissionHint(mode: "default" | "review" | "skip", sandboxed: boolean): string {
	return t(sandboxed ? `perm_${mode}_hint_sandbox` : `perm_${mode}_hint`);
}

export function t(key: MessageKey, params: Record<string, string | number> = {}): string {
	const template = dictionaries[current][key] ?? key;
	return template.replace(/\{(\w+)\}/g, (_, name: string) => String(params[name] ?? ""));
}

/** Re-renders the calling component when the language changes. */
export function useLang(): Lang {
	return useSyncExternalStore(
		(listener) => {
			listeners.add(listener);
			return () => listeners.delete(listener);
		},
		() => current,
	);
}

export function formatNumber(n: number): string {
	return new Intl.NumberFormat(current === "zh" ? "zh-CN" : "en-US").format(n);
}

/** A size on disk in the units Finder uses (1 KB = 1000 bytes): "512 B", "61 KB", "4.3 MB". */
export function formatBytes(bytes: number): string {
	const units = ["B", "KB", "MB", "GB", "TB"];
	let value = Math.max(0, bytes);
	let unit = 0;
	while (value >= 999.5 && unit < units.length - 1) {
		value /= 1000;
		unit += 1;
	}
	const digits = unit > 0 && value < 9.95 ? 1 : 0;
	const number = new Intl.NumberFormat(current === "zh" ? "zh-CN" : "en-US", {
		minimumFractionDigits: digits,
		maximumFractionDigits: digits,
	}).format(value);
	return `${number} ${units[unit]}`;
}

export function formatCost(n: number): string {
	return n < 0.01 && n > 0 ? "<0.01" : n.toFixed(2);
}

/** A time to come or past, with the weekday: "11月10日周二 09:00", "Tue, Nov 10, 09:00". */
export function formatWhen(ms: number): string {
	return new Intl.DateTimeFormat(current === "zh" ? "zh-CN" : "en-US", {
		month: current === "zh" ? "long" : "short",
		day: "numeric",
		weekday: "short",
		hour: "2-digit",
		minute: "2-digit",
		hourCycle: "h23",
	}).format(ms);
}

/** How long ago something happened, short enough for a sidebar row: "5 分钟", "3h", "11月2日". */
export function formatAgo(ms: number, now: number): string {
	const minutes = Math.floor((now - ms) / 60_000);
	if (minutes < 1) return t("justNow");
	if (minutes < 60) return t("minutesAgo", { n: minutes });
	const hours = Math.floor(minutes / 60);
	if (hours < 24) return t("hoursAgo", { n: hours });
	const days = Math.floor(hours / 24);
	if (days < 7) return t("daysAgo", { n: days });
	return new Intl.DateTimeFormat(current === "zh" ? "zh-CN" : "en-US", {
		month: "short",
		day: "numeric",
	}).format(ms);
}

/** How long something has waited for the person, in whole units: "等了 12 分钟", "Waiting 12 min". */
export function formatWaited(ms: number, now: number): string {
	const minutes = Math.floor((now - ms) / 60_000);
	if (minutes < 1) return t("waitedNow");
	if (minutes < 60) return t("waitedMinutes", { n: minutes });
	const hours = Math.floor(minutes / 60);
	if (hours < 24) return t("waitedHours", { n: hours });
	return t("waitedDays", { n: Math.floor(hours / 24) });
}

/** A length of time that ticks by the second: "45 秒", "2 分 05 秒", "1h 02m". */
export function formatElapsed(ms: number): string {
	const total = Math.max(0, Math.floor(ms / 1000));
	const two = (n: number) => String(n).padStart(2, "0");
	const [h, m, s] = [Math.floor(total / 3600), Math.floor((total % 3600) / 60), total % 60];
	if (h > 0) return t("elapsed_hm", { h, m: two(m) });
	if (m > 0) return t("elapsed_ms", { m, s: two(s) });
	return t("elapsed_s", { s });
}

/** The time of day, for "started at 14:05". */
export function formatClock(ms: number): string {
	return new Intl.DateTimeFormat(current === "zh" ? "zh-CN" : "en-US", {
		hour: "2-digit",
		minute: "2-digit",
		hourCycle: "h23",
	}).format(ms);
}

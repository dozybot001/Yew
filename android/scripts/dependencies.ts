// Writes, for every library that goes into the released app (the release runtime classpath in
// app/gradle.lockfile):
//   android/DEPENDENCIES.md                 its version and the license its POM names
//   android/app/src/main/assets/licenses.txt  what the app's "Open source licenses" page shows: the
//                                           libraries by license, each license's text as the libraries
//                                           ship it, and the NOTICE files found in their packages
// The POMs and packages are read from Gradle's cache on this machine, so build the app once first:
//   node android/scripts/dependencies.ts
// LicensesTest fails when the page's text falls behind the lockfile.
import { execFileSync } from "node:child_process";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { join } from "node:path";

const here = new URL("..", import.meta.url).pathname;
const cache = join(homedir(), ".gradle/caches/modules-2/files-2.1");

function pom(group: string, name: string, version: string): string | null {
	const folder = join(cache, group, name, version);
	if (!existsSync(folder)) return null;
	for (const hash of readdirSync(folder)) {
		const file = join(folder, hash, `${name}-${version}.pom`);
		if (existsSync(file)) return readFileSync(file, "utf8");
	}
	return null;
}

/** The licenses a POM names, or those of its parent POM when it names none. */
function licenses(group: string, name: string, version: string, depth = 0): string[] {
	const text = pom(group, name, version);
	if (!text) return [];
	const block = /<licenses>([\s\S]*?)<\/licenses>/.exec(text)?.[1];
	const names = [...(block ?? "").matchAll(/<name>([^<]+)<\/name>/g)].map((m) => (m[1] as string).trim());
	if (names.length > 0 || depth > 3) return names;
	const parent = /<parent>([\s\S]*?)<\/parent>/.exec(text)?.[1];
	if (!parent) return [];
	const field = (tag: string) => new RegExp(`<${tag}>([^<]+)</${tag}>`).exec(parent)?.[1]?.trim() ?? "";
	return licenses(field("groupId"), field("artifactId"), field("version"), depth + 1);
}

const rows = readFileSync(join(here, "app/gradle.lockfile"), "utf8")
	.split("\n")
	.filter((line) => line.includes("releaseRuntimeClasspath"))
	.map((line) => (line.split("=")[0] as string).split(":") as [string, string, string])
	.sort((a, b) => a.join(":").localeCompare(b.join(":")));

const lines = rows.map(([group, name, version]) => {
	const found = licenses(group, name, version);
	return `| ${group}:${name} | ${version} | ${found.length > 0 ? [...new Set(found)].join("; ") : "(not stated in the POM)"} |`;
});
writeFileSync(
	join(here, "DEPENDENCIES.md"),
	`# Yew for Android: third-party libraries

The ${rows.length} libraries on the released app's runtime classpath, from \`app/gradle.lockfile\`, with the license each
library's POM names. Generated by \`scripts/dependencies.ts\`; do not edit. Entries that end in \`-bom\`
only pin versions and carry no code.

| Library | Version | License |
| --- | --- | --- |
${lines.join("\n")}
`,
);
process.stdout.write(`${rows.length} libraries\n`);

// --- The text of the app's "Open source licenses" page ---

/** The files of a library's package (jar, or aar with its classes.jar) whose names say license or notice. */
function shipped(group: string, name: string, version: string): { file: string; text: string }[] {
	const folder = join(cache, group, name, version);
	if (!existsSync(folder)) return [];
	const found: { file: string; text: string }[] = [];
	const wanted = /(^|\/)(notice|license|licence)[^/]*$/i;
	const read = (archive: string) => {
		const entries = execFileSync("unzip", ["-Z1", archive], { encoding: "utf8" }).split("\n");
		for (const entry of entries) {
			if (!wanted.test(entry) || entry.endsWith(".class")) continue;
			const text = execFileSync("unzip", ["-p", archive, entry], { encoding: "utf8" });
			found.push({ file: entry.split("/").at(-1) as string, text: text.replaceAll("\r\n", "\n").trim() });
		}
	};
	for (const hash of readdirSync(folder)) {
		for (const extension of ["jar", "aar"]) {
			const archive = join(folder, hash, `${name}-${version}.${extension}`);
			if (existsSync(archive)) read(archive);
		}
	}
	return found;
}

const kindOf = (license: string) =>
	/apache/i.test(license) ? "apache" : /mit/i.test(license) ? "mit" : /bouncy/i.test(license) ? "bouncy" : /bsd/i.test(license) ? "bsd" : "other";

const apache: string[] = [];
const others: string[] = [];
const notices: string[] = [];
let apacheText = "";
for (const [group, name, version] of rows) {
	const id = `${group}:${name} ${version}`;
	const kinds = new Set(licenses(group, name, version).map(kindOf));
	const files = shipped(group, name, version);
	const license = files.find((file) => /^licen[sc]e/i.test(file.file));
	if (kinds.has("apache")) {
		apache.push(id);
		if (license && /Apache License/.test(license.text) && license.text.length > apacheText.length) apacheText = license.text;
	}
	if (kinds.has("mit") || kinds.has("bouncy")) {
		// These carry their own copyright line, so each one's text is shown as its package ships it.
		if (!license) throw new Error(`${id} ships no license text`);
		others.push(`${id}\n\n${license.text}`);
	}
	if (kinds.has("bsd")) {
		// camera-core names BSD-3-Clause in its POM for the libyuv code built into its native image
		// library, and ships no text for it; the text kept in scripts/notices/libyuv.txt is libyuv's own.
		// Where this comes from; check both again when the camera version changes:
		//   - AndroidX source, camera/camera-core/build.gradle: the library's description says "This
		//     library includes code from libyuv, which is licensed under the BSD-3-Clause license",
		//     and an extraLicense entry declares BSD-3-Clause.
		//   - the LICENSE file at the root of the libyuv repository, which libyuv.txt reproduces.
		if (`${group}:${name}` !== "androidx.camera:camera-core") throw new Error(`${id}: an unexpected BSD license`);
		others.push(`libyuv, built into ${id}\n\n${readFileSync(join(here, "scripts/notices/libyuv.txt"), "utf8").trim()}`);
	}
	if (kinds.has("other") || kinds.size === 0) throw new Error(`${id}: a license this script does not know`);
	for (const file of files) if (/^notice/i.test(file.file)) notices.push(`${id}\n\n${file.text}`);
}
if (!apacheText) throw new Error("no library ships the Apache License text");
const rule = "\n\n────────\n\n";
writeFileSync(
	join(here, "app/src/main/assets/licenses.txt"),
	[
		`Yew for Android includes the open source libraries below. Generated by android/scripts/dependencies.ts.`,
		`Under the Apache License, Version 2.0 (${apache.length} libraries; the license follows the list):\n\n${apache.join("\n")}`,
		apacheText,
		...others,
		...(notices.length > 0 ? [`NOTICE files shipped in these libraries' packages:`, ...notices] : []),
	].join(rule) + "\n",
);
process.stdout.write(`licenses.txt: ${apache.length} Apache-2.0, ${others.length} others, ${notices.length} NOTICE files\n`);
